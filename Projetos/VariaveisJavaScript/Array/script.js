let usuarios = [20, "Carlos", "Maria"];

console.log(usuarios);

//acesando itens
console.log(usuarios[1]);

//adicionando item no final da array
//push()
usuarios.push("Pedro");
console.log(usuarios);

//remove o ultimo item
//pop()
usuarios.pop();
console.log(usuarios);

//remove o primeiro item
//shift
usuarios.shift;
console.log(usuarios);
